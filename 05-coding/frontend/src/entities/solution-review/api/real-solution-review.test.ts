// F5 #4 to #7 against the real wire (SolutionReviewController records): only `api` is faked.
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

const { get, post } = vi.hoisted(() => ({ get: vi.fn(), post: vi.fn() }));
vi.mock("@/shared/api", async (importOriginal) => ({
  ...(await importOriginal<Record<string, unknown>>()),
  api: { get, post },
}));

import { ApiError } from "@/shared/api";
import {
  CLIENT_TIMEOUT_MS,
  IN_PROGRESS_MAX_RETRIES,
  IN_PROGRESS_WAIT_MS,
  getRealRecentReviews,
  getRealReviewQuickInsight,
  getRealReviewedProblemIds,
  getRealSolutionReview,
  toVerdict,
} from "./real-solution-review";

const SUBMISSION = "6f1c2b0e-0000-4000-8000-000000000001";

const wire = {
  id: "r1",
  submissionId: SUBMISSION,
  problemId: "p1",
  language: "PYTHON",
  createdAt: "2026-11-12T03:00:00Z",
  servedFromCache: false,
  isReferenceOnly: true,
  readabilityScore: 4,
  schemaVersion: "1",
  approachTitle: "hash map",
  verdict: "IMPROVABLE",
  isApproachOptimal: false,
  complexity: {
    actualTime: "O(n^2)",
    optimalTime: "O(n)",
    timeExplanation: "Hai vòng lặp",
    actualSpace: "O(1)",
    optimalSpace: null,
    spaceExplanation: "Không dùng thêm bộ nhớ",
  },
  strengths: ["Dễ đọc"],
  improvements: ["Dùng dict"],
  edgeCases: ["Mảng rỗng"],
  followUpTopics: ["hash map"],
  codeDiff: { suggestedCode: "x = 1\n", explanation: "Gọn hơn" },
};

beforeEach(() => {
  get.mockReset();
  post.mockReset();
});
afterEach(() => {
  vi.useRealTimers();
});

describe("getRealSolutionReview (#4)", () => {
  it("posts to the submission path without a body and maps the report", async () => {
    post.mockResolvedValue(wire);

    const review = await getRealSolutionReview(SUBMISSION);

    expect(post).toHaveBeenCalledTimes(1);
    const [path, body, options] = post.mock.calls[0]!;
    expect(path).toBe(`/ai/submissions/${SUBMISSION}/solution-review`);
    // A submission is data, never an instruction: nothing but the id travels, no source code.
    expect(body).toBeUndefined();
    expect(options.signal).toBeInstanceOf(AbortSignal);
    expect(review).toEqual({
      submissionId: SUBMISSION,
      problemId: "p1",
      languageKey: "python",
      readabilityScore: 4,
      createdAt: "2026-11-12T03:00:00Z",
      schemaVersion: "1",
      approachTitle: "hash map",
      verdict: "IMPROVABLE",
      isApproachOptimal: false,
      complexity: {
        actualTime: "O(n^2)",
        optimalTime: "O(n)",
        timeExplanation: "Hai vòng lặp",
        actualSpace: "O(1)",
        optimalSpace: null,
        spaceExplanation: "Không dùng thêm bộ nhớ",
      },
      strengths: ["Dễ đọc"],
      improvements: ["Dùng dict"],
      edgeCases: ["Mảng rỗng"],
      followUpTopics: ["hash map"],
      codeDiff: { suggestedCode: "x = 1\n", explanation: "Gọn hơn" },
    });
    // Fields no screen reads are dropped, and nothing about problem title or source is invented.
    expect(review).not.toHaveProperty("servedFromCache");
    expect(review).not.toHaveProperty("source");
  });

  it("maps a null codeDiff (optimal approach) to two nulls and lower-cases the language", async () => {
    post.mockResolvedValue({ ...wire, language: "CPP", codeDiff: null });

    const review = await getRealSolutionReview(SUBMISSION);

    expect(review.languageKey).toBe("cpp");
    expect(review.codeDiff).toEqual({ suggestedCode: null, explanation: null });
  });

  it.each([
    ["AIR-101", 404],
    ["AIR-102", 422],
    ["AIR-302", 403],
    ["AIR-401", 429],
    ["AIR-402", 429],
    ["AIR-404", 429],
    ["AIR-501", 503],
    ["AIR-502", 502],
    ["AIR-V01", 400],
  ])("rethrows %s as the same ApiError without retrying", async (code, status) => {
    post.mockRejectedValue(new ApiError(code, status, "x", { retryAfterSeconds: 7 }));

    await expect(getRealSolutionReview(SUBMISSION)).rejects.toMatchObject({
      code,
      status,
      details: { retryAfterSeconds: 7 },
    });
    expect(post).toHaveBeenCalledTimes(1);
  });

  it("waits 3 s and asks again on AIR-103 (report generated by another call)", async () => {
    vi.useFakeTimers();
    post
      .mockRejectedValueOnce(new ApiError("AIR-103", 409))
      .mockRejectedValueOnce(new ApiError("AIR-103", 409))
      .mockResolvedValueOnce(wire);

    const result = getRealSolutionReview(SUBMISSION);
    await vi.advanceTimersByTimeAsync(IN_PROGRESS_WAIT_MS - 1);
    expect(post).toHaveBeenCalledTimes(1);
    await vi.advanceTimersByTimeAsync(1);
    expect(post).toHaveBeenCalledTimes(2);
    await vi.advanceTimersByTimeAsync(IN_PROGRESS_WAIT_MS);

    await expect(result).resolves.toMatchObject({ problemId: "p1" });
    expect(post).toHaveBeenCalledTimes(3);
  });

  it("gives up on AIR-103 after ten calls with a transient AIR-501", async () => {
    vi.useFakeTimers();
    post.mockRejectedValue(new ApiError("AIR-103", 409));

    const result = getRealSolutionReview(SUBMISSION);
    const settled = result.catch((error: unknown) => error);
    await vi.advanceTimersByTimeAsync(IN_PROGRESS_WAIT_MS * IN_PROGRESS_MAX_RETRIES);

    expect(await settled).toMatchObject({ code: "AIR-501", status: 503 });
    expect(post).toHaveBeenCalledTimes(IN_PROGRESS_MAX_RETRIES);
  });

  it("turns the 40 s client limit into a transient AIR-501", async () => {
    vi.useFakeTimers();
    post.mockImplementation(
      (_path: string, _body: unknown, options: { signal: AbortSignal }) =>
        new Promise((_resolve, reject) => {
          options.signal.addEventListener("abort", () => reject(options.signal.reason));
        }),
    );

    const settled = getRealSolutionReview(SUBMISSION).catch((error: unknown) => error);
    await vi.advanceTimersByTimeAsync(CLIENT_TIMEOUT_MS);

    expect(await settled).toMatchObject({ code: "AIR-501", status: 503 });
  });

  it("propagates the abort when the caller leaves the screen (no AIR-501)", async () => {
    const controller = new AbortController();
    post.mockImplementation(
      (_path: string, _body: unknown, options: { signal: AbortSignal }) =>
        new Promise((_resolve, reject) => {
          options.signal.addEventListener("abort", () => reject(options.signal.reason));
        }),
    );

    const settled = getRealSolutionReview(SUBMISSION, controller.signal).catch(
      (error: unknown) => error,
    );
    controller.abort(new Error("left"));

    expect(await settled).toMatchObject({ message: "left" });
  });
});

describe("toVerdict", () => {
  it("keeps a known verdict and falls back on isApproachOptimal for an unknown one", () => {
    expect(toVerdict("NOT_OPTIMAL")).toBe("NOT_OPTIMAL");
    expect(toVerdict("", true)).toBe("OPTIMAL");
    expect(toVerdict("")).toBe("IMPROVABLE");
  });
});

describe("#5 problem ids, #6 quick insight, #7 recent", () => {
  it("reads the reviewed problem ids", async () => {
    get.mockResolvedValue({ problemIds: ["p1", "p2"] });

    expect(await getRealReviewedProblemIds()).toEqual(["p1", "p2"]);
    expect(get).toHaveBeenCalledWith("/ai/me/solution-reviews/problem-ids");
  });

  it("sends problemId and maps the quick insight, dropping ids and dates it does not show", async () => {
    get.mockResolvedValue({
      review: {
        submissionId: "s1",
        reviewId: "r1",
        timeComplexity: "O(n)",
        spaceComplexity: "O(1)",
        verdict: "OPTIMAL",
        createdAt: "2026-11-12T03:00:00Z",
        isReferenceOnly: true,
      },
    });

    expect(await getRealReviewQuickInsight("p1")).toEqual({
      submissionId: "s1",
      timeComplexity: "O(n)",
      spaceComplexity: "O(1)",
      verdict: "OPTIMAL",
    });
    expect(get).toHaveBeenCalledWith("/ai/me/solution-reviews/quick-insight", {
      problemId: "p1",
    });
  });

  it("returns null when the problem has no review", async () => {
    get.mockResolvedValue({ review: null });

    expect(await getRealReviewQuickInsight("p1")).toBeNull();
  });

  it("maps the recent items and sends limit only when given", async () => {
    get.mockResolvedValue({
      items: [
        {
          reviewId: "r1",
          submissionId: "s1",
          problemId: "p1",
          problemTitle: "Two Sum",
          verdict: "OPTIMAL",
          timeComplexity: "O(n)",
          createdAt: "2026-11-12T03:00:00Z",
        },
      ],
    });

    expect(await getRealRecentReviews()).toEqual([
      {
        submissionId: "s1",
        problemTitle: "Two Sum",
        verdict: "OPTIMAL",
        timeComplexity: "O(n)",
        createdAt: "2026-11-12T03:00:00Z",
      },
    ]);
    expect(get).toHaveBeenLastCalledWith("/ai/me/solution-reviews/recent", undefined);
    await getRealRecentReviews(5);
    expect(get).toHaveBeenLastCalledWith("/ai/me/solution-reviews/recent", { limit: 5 });
  });

  it.each(["AIR-V01", "AIR-V02"])("lets %s from the quick-insight and recent calls through", async (code) => {
    get.mockRejectedValue(new ApiError(code, 400));

    await expect(getRealReviewQuickInsight("x")).rejects.toMatchObject({ code });
    await expect(getRealRecentReviews(99)).rejects.toMatchObject({ code });
  });
});
